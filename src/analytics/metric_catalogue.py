def get_metric_catalogue() -> List[Dict[str, Any]]:
    """Return the full list of 18 canonical KPI definitions."""
    return METRIC_CATALOGUE


def get_metric_by_id(metric_id: str) -> Dict[str, Any]:
    """Retrieve a single KPI definition by its ID (e.g. 'KPI-004')."""
    for item in METRIC_CATALOGUE:
        if item["metric_id"] == metric_id:
            return item
    raise KeyError(f"Metric ID {metric_id} not found in METRIC_CATALOGUE.")


def export_metric_catalogue_markdown(output_path: Path | None = None) -> Path:
    """Generate docs/metric_catalogue.md from the centralized metric layer."""
    target = output_path or (DOCS_DIR / "metric_catalogue.md")
    target.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "# Centralised KPI Catalogue & Metric Governance Layer",
        "",
        "**Product:** E-COMMERCE INTELLIGENCE OS — AI-Powered Business Intelligence & Decision Platform  ",
        "**Source Module:** `src/analytics/metric_catalogue.py`  ",
        "**Currency:** Brazilian Real (`BRL` / `R$`)  ",
        "**Governance Rules Enforced:** `D-1` (Revenue Proxy vs Item Price), `D-2` (Jan 2017 – Aug 2018 Trend Window), `D-3` (Latest Review Deduplication), `D-4` (74-Category Mapping), `D-5` (Multi-Day Repeat Customer Rule)",
        "",
        "---",
        "",
        "## 1. Summary Table of Canonical KPIs",
        "",
        "| KPI ID | Metric Name | Category | Canonical Value | Window Value (Jan 17–Aug 18) | Unit | Grain |",
        "| :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
    ]

    for m in METRIC_CATALOGUE:
        win_val = m["window_value"] if m["window_value"] is not None else "Full Dataset"
        if isinstance(win_val, float) and "BRL" in m["unit"]:
            win_str = f"R$ {win_val:,.2f}"
        elif isinstance(win_val, int):
            win_str = f"{win_val:,}"
        else:
            win_str = str(win_val)
        lines.append(
            f"| `{m['metric_id']}` | **{m['metric_name']}** | {m['category']} | **{m['formatted_value']}** | {win_str} | {m['unit']} | {m['grain']} |"
        )

    lines.extend(["", "---", "", "## 2. Detailed KPI Specifications", ""])

    for m in METRIC_CATALOGUE:
        lines.extend(
            [
                f"### {m['metric_id']} — {m['metric_name']}",
                f"- **Domain Category:** {m['category']}",
                f"- **Canonical Verified Value:** `{m['formatted_value']}` (Raw: `{m['canonical_value']}`)",
                f"- **Business Definition:** {m['business_definition']}",
                f"- **SQL Formula:** `{m['sql_formula']}`",
                f"- **Python Formula:** `{m['python_formula']}`",
                f"- **Source Tables:** `{', '.join(m['source_tables'])}`",
                f"- **Filters (Inclusions / Exclusions):** {m['filters']}",
                f"- **Aggregation Grain:** {m['grain']}",
                f"- **Unit / Currency:** {m['unit']}",
                f"- **Analysis Window:** {m['analysis_window']}",
                f"- **Null-Handling Rule:** {m['null_handling']}",
                f"- **Known Limitations & Caveats:** {m['known_limitations']}",
                "",
            ]
        )

